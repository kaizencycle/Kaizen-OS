#!/usr/bin/env node
/**
 * Generate docs/INDEX.md from mkdocs.yml nav (C-381).
 * Hand-editing INDEX.md is not permitted once this ships.
 *
 * Usage: node scripts/generate-handbook-index.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseMkdocsNav, readMkdocs } from './lib/docs-nav.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'INDEX.md');
const CHECK = process.argv.includes('--check');

const cycle = JSON.parse(fs.readFileSync(path.join(ROOT, 'cycle.json'), 'utf8'));
const currentCycle = cycle.current_cycle;
const date = cycle.date || new Date().toISOString().slice(0, 10);
const nav = parseMkdocsNav(readMkdocs(ROOT));

const lines = [
  '<!-- GENERATED by scripts/generate-handbook-index.mjs — do not edit by hand -->',
  '',
  '# Mobius Handbook — Generated Index',
  '',
  `**Cycle:** ${currentCycle}  `,
  `**Generated:** ${date}  `,
  `**Source of truth:** [\`mkdocs.yml\`](../mkdocs.yml) navigation`,
  '',
  '> This file is a build artifact. Edit navigation in `mkdocs.yml`, then run `npm run docs:generate-index`.',
  '',
  '---',
  '',
  '## Live entry points',
  '',
  '| Page | Path |',
  '|------|------|',
  '| [Handbook home](https://handbook.mobius-substrate.com/00-START-HERE/) | `00-START-HERE/README.md` |',
  '| [State of the Substrate (latest)](https://handbook.mobius-substrate.com/STATE_OF_THE_SUBSTRATE_LATEST/) | `STATE_OF_THE_SUBSTRATE_LATEST.md` |',
  '| [AI Simple in Life](https://handbook.mobius-substrate.com/00-START-HERE/AI_SIMPLE_IN_LIFE/) | `00-START-HERE/AI_SIMPLE_IN_LIFE.md` |',
  '',
  '---',
  '',
  '## Navigation map',
  '',
];

let section = '';
for (const entry of nav) {
  const parts = entry.path.split('/');
  const top = parts[0];
  if (top !== section) {
    section = top;
    lines.push(`### ${section}`, '');
  }
  const href = `./${entry.path}`;
  lines.push(`- [${entry.title}](${href}) — \`${entry.path}\``);
}
lines.push('', '---', '', `*Generated for cycle ${currentCycle}. "We heal as we walk."*`, '');

const content = `${lines.join('\n')}\n`;

if (CHECK) {
  if (!fs.existsSync(OUT)) {
    console.error('❌ docs/INDEX.md missing — run npm run docs:generate-index');
    process.exit(1);
  }
  const existing = fs.readFileSync(OUT, 'utf8');
  if (existing !== content) {
    console.error('❌ docs/INDEX.md is out of date — run npm run docs:generate-index');
    process.exit(1);
  }
  console.log('✅ docs/INDEX.md is up to date.');
  process.exit(0);
}

fs.writeFileSync(OUT, content, 'utf8');
console.log(`Generated ${path.relative(ROOT, OUT)} (${nav.length} nav entries, ${currentCycle}).`);
